def evaluate_all(test_cases, meta_list, metrics) -> list[dict]:
    rows = []
    for i, tc in enumerate(test_cases):
        meta = meta_list[i]
        scores, reasons = {}, {}
        for metric in metrics:
            try:
                metric.measure(tc)
                scores[metric.name] = round(metric.score, 3) if metric.score is not None else None
                reasons[metric.name] = getattr(metric, "reason", None)
                logger.info("  [%d] %s = %s", meta["result_id"], metric.name, scores[metric.name])
            except Exception as exc:
                logger.error("  [%d] Ошибка «%s»: %s", meta["result_id"], metric.name, exc)
                scores[metric.name] = None
                reasons[metric.name] = str(exc)
        rows.append({"meta": meta, "scores": scores, "reasons": reasons})
    return rows


def _print_table(rows, metric_names):
    W = 22
    header = f"{'ID':<6} {'Дисциплина':<28} {'Оц':<4}" + "".join(f"  {n[:W]:<{W}}" for n in metric_names)
    sep = "-" * len(header)
    print("\n" + "=" * len(header))
    print(header)
    print(sep)
    for row in rows:
        m = row["meta"]
        line = f"{m['result_id']:<6} {str(m['discipline'])[:27]:<28} {int(m['rec_grade']):<4}"
        for n in metric_names:
            s = row["scores"].get(n)
            line += f"  {(f'{s:.3f}' if s is not None else 'N/A'):<{W}}"
        print(line)
    print(sep)
    sums = {n: 0.0 for n in metric_names}
    cnts = {n: 0 for n in metric_names}
    for row in rows:
        for n in metric_names:
            s = row["scores"].get(n)
            if s is not None:
                sums[n] += s; cnts[n] += 1
    avg_line = f"{'СРЕДНЕЕ':<40}" + "".join(
        f"  {(sums[n]/cnts[n] if cnts[n] else float('nan')):.3f}{'':<{W-5}}" for n in metric_names
    )
    print(avg_line)
    print("=" * len(header))


def _save_json(rows, metric_names, path="results.json"):
    sums = {n: 0.0 for n in metric_names}
    cnts = {n: 0 for n in metric_names}
    for row in rows:
        for n in metric_names:
            s = row["scores"].get(n)
            if s is not None:
                sums[n] += s; cnts[n] += 1
    out = {
        "total_cases": len(rows),
        "averages": {n: round(sums[n]/cnts[n], 3) if cnts[n] else None for n in metric_names},
        "cases": rows,
    }
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    logger.info("Результаты сохранены в %s", path)


