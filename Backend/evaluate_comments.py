CLAUDE_MODEL = os.getenv("CLAUDE_MODEL", "claude-sonnet-4-6")


def _parse_as_schema(text: str, schema: Type[BaseModel]) -> BaseModel:
    def _try(raw: str) -> Optional[BaseModel]:
        try:
            return schema(**json.loads(raw))
        except Exception:
            return None
    if r := _try(text):
        return r
    if m := re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL):
        if r := _try(m.group(1)):
            return r
    if m := re.search(r"\{.*?\}", text, re.DOTALL):
        if r := _try(m.group(0)):
            return r
    raise ValueError(f"Не удалось распарсить как {schema.__name__}: {text[:200]!r}")


class ClaudeJudge(DeepEvalBaseLLM):
    def __init__(self, model: str = CLAUDE_MODEL) -> None:
        self._model = model
        self._client: Optional[anthropic.Anthropic] = None

    def load_model(self) -> Any:
        self._client = anthropic.Anthropic()
        return self._client

    def _cli(self) -> anthropic.Anthropic:
        if self._client is None:
            self.load_model()
        return self._client  # type: ignore[return-value]

    def _call(self, prompt: str, want_json: bool) -> str:
        system = "Ты — строгий эксперт-оценщик качества образовательных комментариев."
        if want_json:
            system += " Отвечай ТОЛЬКО валидным JSON-объектом без пояснений и обёрток."
        msg = self._cli().messages.create(
            model=self._model,
            max_tokens=1024,
            system=system,
            messages=[{"role": "user", "content": prompt}],
        )
        return msg.content[0].text.strip()

    async def _call_async(self, prompt: str, want_json: bool) -> str:
        system = "Ты — строгий эксперт-оценщик качества образовательных комментариев."
        if want_json:
            system += " Отвечай ТОЛЬКО валидным JSON-объектом без пояснений и обёрток."
        async with anthropic.AsyncAnthropic() as ac:
            msg = await ac.messages.create(
                model=self._model,
                max_tokens=1024,
                system=system,
                messages=[{"role": "user", "content": prompt}],
            )
        return msg.content[0].text.strip()

    def generate(self, prompt: str, schema: Optional[Type[BaseModel]] = None, **kwargs) -> Any:
        try:
            text = self._call(prompt, want_json=schema is not None)
        except Exception as e:
            logger.error("ClaudeJudge.generate error: %s", e); raise
        return _parse_as_schema(text, schema) if schema else text

    async def a_generate(self, prompt: str, schema: Optional[Type[BaseModel]] = None, **kwargs) -> Any:
        try:
            text = await self._call_async(prompt, want_json=schema is not None)
        except Exception as e:
            logger.error("ClaudeJudge.a_generate error: %s", e); raise
        return _parse_as_schema(text, schema) if schema else text

    def get_model_name(self) -> str:
        return f"Claude ({self._model})"


def build_metrics(judge: ClaudeJudge) -> list[GEval]:
    return [
        GEval(
            name="Достоверность",
            model=judge,
            criteria=(
                "Оцени, насколько комментарий к ответу студента достоверен. "
                "Комментарий должен опираться ТОЛЬКО на то, что явно присутствует "
                "в тексте ответа студента (поле context), без приписывания ему "
                "ошибок или знаний, которых нет в его ответе. "
                "Высокая оценка: комментарий не выходит за рамки реального ответа. "
                "Низкая оценка: комментарий содержит домыслы или несуществующие ошибки."
            ),
            evaluation_params=[SingleTurnParams.INPUT, SingleTurnParams.ACTUAL_OUTPUT, SingleTurnParams.CONTEXT],
        ),
        GEval(
            name="Полезность",
            model=judge,
            criteria=(
                "Оцени практическую полезность комментария для преподавателя. "
                "Комментарий должен содержать конкретный анализ расхождений между "
                "ответом студента и эталонным ответом (expected_output), "
                "а не размытые формулировки вроде «ответ неполный» или «некоторые аспекты не раскрыты». "
                "Высокая оценка: указаны конкретные пробелы и сильные стороны. "
                "Низкая оценка: только общие слова без конкретики."
            ),
            evaluation_params=[SingleTurnParams.INPUT, SingleTurnParams.ACTUAL_OUTPUT, SingleTurnParams.EXPECTED_OUTPUT],
        ),
        GEval(
            name="Соответствие оценке",
            model=judge,
            criteria=(
                "Оцени, насколько тон и акценты комментария соответствуют рекомендуемой оценке, "
                "указанной в конце поля input (строка «Рекомендуемая оценка: N»). "
                "При оценке 2–3 комментарий должен акцентировать серьёзные пробелы. "
                "При оценке 4–5 — отмечать достоинства и лишь незначительные недостатки. "
                "Высокая оценка: тон согласован с числовой оценкой. "
                "Низкая оценка: явное противоречие между оценкой и тональностью."
            ),
            evaluation_params=[SingleTurnParams.INPUT, SingleTurnParams.ACTUAL_OUTPUT],
        ),
    ]

